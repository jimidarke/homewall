#!/usr/bin/env python3
"""Regenerate the tablet's MDI glyph subset.

Fetches the 39 glyphs of Contract section 2.1 from the pinned @mdi/svg release, pulls the single path
`d` out of each SVG, and writes:

  app/src/main/java/io/haku/tablet/ui/glyph/GlyphData.kt     internal val GLYPH_PATHS
  app/src/main/assets/licenses/MDI-LICENSE.txt               the MDI licence text

Standard library only; safe to run from any directory and to re-run (the output is deterministic).
To add a glyph: add it to GLYPHS (and to Contract section 2.1), run this, commit the result.
To bump MDI: change MDI_VERSION, re-run, and review the diff.
"""
import re
import sys
import urllib.request
from pathlib import Path

MDI_VERSION = "7.4.47"
CDN = f"https://cdn.jsdelivr.net/npm/@mdi/svg@{MDI_VERSION}"

# Contract section 2.1, in table order, then the photo peek's chevrons (0.4.0, DESIGN section 8.10).
GLYPHS = [
    # Doors
    "door-open", "door-closed", "door",
    # Laundry
    "washing-machine", "tumble-dryer",
    # Water, energy, gas
    "water", "water-outline", "flash", "fire", "meter-gas",
    # Climate
    "snowflake", "fan", "thermostat",
    # Cards
    "calendar", "history",
    # Activity
    "motion-sensor", "motion-sensor-off", "lock", "lock-open-variant", "home-account", "account-arrow-right",
    # Weather
    "alert-circle-outline", "weather-sunny", "weather-night", "weather-partly-cloudy",
    "weather-night-partly-cloudy", "weather-cloudy", "weather-fog", "weather-hail", "weather-lightning",
    "weather-lightning-rainy", "weather-pouring", "weather-rainy", "weather-snowy", "weather-snowy-rainy",
    "weather-windy", "weather-windy-variant",
    # Photo peek
    "chevron-left", "chevron-right",
]

ROOT = Path(__file__).resolve().parent.parent
OUT_KT = ROOT / "app/src/main/java/io/haku/tablet/ui/glyph/GlyphData.kt"
OUT_LICENSE = ROOT / "app/src/main/assets/licenses/MDI-LICENSE.txt"

PATH_D = re.compile(r'\sd="([^"]+)"')
VIEW_BOX = re.compile(r'viewBox="0 0 24 24"')


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read().decode("utf-8")


def path_data(name: str) -> str:
    svg = fetch(f"{CDN}/svg/{name}.svg")
    if not VIEW_BOX.search(svg):
        sys.exit(f"{name}: expected a 24x24 viewBox, got: {svg[:200]!r}")
    found = PATH_D.findall(svg)
    if len(found) != 1:
        sys.exit(f"{name}: expected exactly one path d attribute, found {len(found)}")
    return found[0].strip()


def kotlin_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main() -> None:
    if len(set(GLYPHS)) != len(GLYPHS):
        sys.exit("duplicate glyph name in GLYPHS")
    lines = [
        "// GENERATED by tools/gen-glyphs.py. Do not edit; re-run the script.",
        f"// Path data from @mdi/svg {MDI_VERSION} (Material Design Icons, Apache-2.0).",
        "// Licence text: app/src/main/assets/licenses/MDI-LICENSE.txt",
        "// Every path is drawn in a 24x24 viewport.",
        "package io.haku.tablet.ui.glyph",
        "",
        "internal val GLYPH_PATHS: Map<String, String> = mapOf(",
    ]
    for name in GLYPHS:
        lines.append(f"    {kotlin_string(name)} to {kotlin_string(path_data(name))},")
    lines += [")", ""]
    OUT_KT.parent.mkdir(parents=True, exist_ok=True)
    OUT_KT.write_text("\n".join(lines), encoding="utf-8")

    OUT_LICENSE.parent.mkdir(parents=True, exist_ok=True)
    licence = fetch(f"{CDN}/LICENSE")
    OUT_LICENSE.write_text(licence if licence.endswith("\n") else licence + "\n", encoding="utf-8")

    print(f"wrote {len(GLYPHS)} glyphs to {OUT_KT.relative_to(ROOT)} and the licence to {OUT_LICENSE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
