#!/usr/bin/env python3
"""Rasterize the tablet's MDI glyph set into white PNGs for the Roku channel.

The tablet ships the path data (fire-tablet/.../ui/glyph/GlyphData.kt, generated by
fire-tablet/tools/gen-glyphs.py from @mdi/svg 7.4.47); this reads it, so both clients
draw the same glyphs. Each glyph is filled white on transparent (nonzero winding, like
SVG) and the channel tints it with Poster.blendColor.

Writes:
  roku/images/glyphs/<px>/<name>.png   one per glyph per size in SIZES
  roku/source/Glyphs.brs               HK_GLYPHS(): the names, so the channel can tell a
                                       missing glyph from a known one

Needs matplotlib and Pillow (no SVG rasterizer): run it with the sidecar's venv,
    sidecar/.venv/bin/python roku/scripts/gen_glyphs.py
Deterministic; re-run after the tablet's glyph set changes and commit the result.
"""
import io
import math
import re
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import PathPatch  # noqa: E402
from matplotlib.path import Path as MPath  # noqa: E402
from PIL import Image  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
GLYPH_KT = REPO / "fire-tablet/app/src/main/java/io/haku/tablet/ui/glyph/GlyphData.kt"
OUT = REPO / "roku/images/glyphs"
OUT_BRS = REPO / "roku/source/Glyphs.brs"

# Card chips (40), activity marks and laundry lines (32), the forecast strip (56).
SIZES = (32, 40, 56)

# Roku-only glyphs, from the same pinned @mdi/svg 7.4.47 (Apache-2.0).
EXTRA_PATHS = {
    "cctv": "M6.03 12.03L8.03 15.5L5.5 18.68L2 12.62L6.03 12.03M17 18V15.29C17.88 14.9 18.5 "
            "14.03 18.5 13C18.5 12.43 18.3 11.9 17.97 11.5L19.94 10.35C20.95 9.76 21.3 8.47 "
            "20.71 7.46L19.33 5.06C18.74 4.05 17.45 3.7 16.44 4.28L8.31 9C7.36 9.53 7.03 10.75 "
            "7.58 11.71L9.08 14.31C9.63 15.26 10.86 15.59 11.81 15.04L13.69 13.96C13.94 14.55 "
            "14.41 15.03 15 15.29V18C15 19.1 15.9 20 17 20H22V18H17Z",
}

ENTRY = re.compile(r'^\s*"([a-z0-9-]+)" to "([^"]+)",?\s*$', re.M)
NUMBER = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def read_paths():
    paths = dict(ENTRY.findall(GLYPH_KT.read_text(encoding="utf-8")))
    if not paths:
        sys.exit(f"no glyph paths found in {GLYPH_KT}")
    return {**paths, **EXTRA_PATHS}


class _Scanner:
    """Reads SVG path data: commands, numbers, and single-digit arc flags."""

    def __init__(self, d):
        self.d, self.i = d, 0

    def _skip(self):
        while self.i < len(self.d) and self.d[self.i] in " ,\t\r\n":
            self.i += 1

    def done(self):
        self._skip()
        return self.i >= len(self.d)

    def command(self):
        """The next command letter, or None when a number follows (an implicit repeat)."""
        self._skip()
        c = self.d[self.i]
        if c.isalpha():
            self.i += 1
            return c
        return None

    def number(self):
        self._skip()
        m = NUMBER.match(self.d, self.i)
        if not m:
            raise ValueError(f"expected a number at {self.i}: {self.d[self.i:self.i + 20]!r}")
        self.i = m.end()
        return float(m.group())

    def flag(self):
        """Arc flags are one character, and may be run together ("011")."""
        self._skip()
        c = self.d[self.i]
        if c not in "01":
            raise ValueError(f"expected an arc flag at {self.i}")
        self.i += 1
        return int(c)


def _arc_to_cubics(x1, y1, rx, ry, phi, fa, fs, x2, y2):
    """Endpoint-parameterized SVG arc -> cubic segments (SVG spec appendix F.6)."""
    if (x1, y1) == (x2, y2):
        return []
    if rx == 0 or ry == 0:
        return [((x1, y1), (x2, y2), (x2, y2))]
    rx, ry = abs(rx), abs(ry)
    cp, sp = math.cos(math.radians(phi)), math.sin(math.radians(phi))
    dx, dy = (x1 - x2) / 2, (y1 - y2) / 2
    x1p, y1p = cp * dx + sp * dy, -sp * dx + cp * dy
    lam = (x1p ** 2) / (rx ** 2) + (y1p ** 2) / (ry ** 2)
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx * rx * ry * ry - rx * rx * y1p * y1p - ry * ry * x1p * x1p
    den = rx * rx * y1p * y1p + ry * ry * x1p * x1p
    coef = math.sqrt(max(0.0, num / den)) if den else 0.0
    if fa == fs:
        coef = -coef
    cxp, cyp = coef * rx * y1p / ry, -coef * ry * x1p / rx
    cx = cp * cxp - sp * cyp + (x1 + x2) / 2
    cy = sp * cxp + cp * cyp + (y1 + y2) / 2

    def ang(ux, uy, vx, vy):
        return math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)

    t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not fs and dt > 0:
        dt -= 2 * math.pi
    elif fs and dt < 0:
        dt += 2 * math.pi
    segs = max(1, math.ceil(abs(dt) / (math.pi / 2) - 1e-9))
    step = dt / segs
    k = 4 / 3 * math.tan(step / 4)

    def pt(t):
        x, y = rx * math.cos(t), ry * math.sin(t)
        return cp * x - sp * y + cx, sp * x + cp * y + cy

    def deriv(t):
        x, y = -rx * math.sin(t), ry * math.cos(t)
        return cp * x - sp * y, sp * x + cp * y

    out, t = [], t1
    for _ in range(segs):
        p0, p3 = pt(t), pt(t + step)
        d0, d3 = deriv(t), deriv(t + step)
        out.append(((p0[0] + k * d0[0], p0[1] + k * d0[1]),
                    (p3[0] - k * d3[0], p3[1] - k * d3[1]), p3))
        t += step
    out[-1] = (out[-1][0], out[-1][1], (x2, y2))     # land exactly on the endpoint
    return out


def to_mpl_path(d):
    """An SVG path `d` -> matplotlib Path (absolute coords, 24x24 viewport)."""
    sc = _Scanner(d)
    verts, codes = [], []
    cmd = None
    cur = start = (0.0, 0.0)
    last_ctrl, last_cmd = None, None

    while not sc.done():
        c = sc.command()
        if c is not None:
            cmd = c
        elif cmd is None:
            raise ValueError("path data must start with a command")
        elif cmd in "Zz":
            raise ValueError("numbers after Z")
        up, rel = cmd.upper(), cmd.islower()
        ox, oy = cur if rel else (0.0, 0.0)

        if up == "Z":
            codes.append(MPath.CLOSEPOLY)
            verts.append(start)
            cur, last_ctrl, last_cmd = start, None, "Z"
        elif up == "M":
            cur = start = (sc.number() + ox, sc.number() + oy)
            verts.append(cur)
            codes.append(MPath.MOVETO)
            cmd = "l" if rel else "L"                       # implicit lineto after a moveto
            last_ctrl, last_cmd = None, "M"
        elif up == "L":
            cur = (sc.number() + ox, sc.number() + oy)
            verts.append(cur)
            codes.append(MPath.LINETO)
            last_ctrl, last_cmd = None, "L"
        elif up == "H":
            cur = (sc.number() + ox, cur[1])
            verts.append(cur)
            codes.append(MPath.LINETO)
            last_ctrl, last_cmd = None, "H"
        elif up == "V":
            cur = (cur[0], sc.number() + oy)
            verts.append(cur)
            codes.append(MPath.LINETO)
            last_ctrl, last_cmd = None, "V"
        elif up in ("C", "S"):
            if up == "C":
                c1 = (sc.number() + ox, sc.number() + oy)
            else:
                c1 = (2 * cur[0] - last_ctrl[0], 2 * cur[1] - last_ctrl[1]) \
                    if last_cmd in ("C", "S") else cur
            c2 = (sc.number() + ox, sc.number() + oy)
            p = (sc.number() + ox, sc.number() + oy)
            verts += [c1, c2, p]
            codes += [MPath.CURVE4] * 3
            last_ctrl, cur, last_cmd = c2, p, up
        elif up in ("Q", "T"):
            if up == "Q":
                q = (sc.number() + ox, sc.number() + oy)
            else:
                q = (2 * cur[0] - last_ctrl[0], 2 * cur[1] - last_ctrl[1]) \
                    if last_cmd in ("Q", "T") else cur
            p = (sc.number() + ox, sc.number() + oy)
            verts += [q, p]
            codes += [MPath.CURVE3] * 2
            last_ctrl, cur, last_cmd = q, p, up
        elif up == "A":
            rx, ry, phi = sc.number(), sc.number(), sc.number()
            fa, fs = sc.flag(), sc.flag()
            p = (sc.number() + ox, sc.number() + oy)
            for c1, c2, q in _arc_to_cubics(cur[0], cur[1], rx, ry, phi, fa, fs, p[0], p[1]):
                verts += [c1, c2, q]
                codes += [MPath.CURVE4] * 3
            cur, last_ctrl, last_cmd = p, None, "A"
        else:
            raise ValueError(f"unsupported path command {cmd!r}")
    return MPath(verts, codes)


def render(path, px):
    """White glyph on transparent, px x px, the 24x24 viewport filling the canvas."""
    dpi = 100
    fig = plt.figure(figsize=(px / dpi, px / dpi), dpi=dpi)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 24)
    ax.set_ylim(24, 0)
    ax.axis("off")
    ax.add_patch(PathPatch(path, facecolor="white", edgecolor="none", lw=0))
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=dpi, transparent=True)
    plt.close(fig)
    img = Image.open(io.BytesIO(buf.getvalue())).convert("RGBA")
    if img.size != (px, px):
        raise SystemExit(f"rendered {img.size}, expected {px}x{px}")
    alpha = img.getchannel("A")
    white = Image.new("RGBA", img.size, (255, 255, 255, 0))
    white.putalpha(alpha)                  # pure white RGB: blendColor tints it exactly
    return white


def main():
    paths = read_paths()
    for px in SIZES:
        out = OUT / str(px)
        out.mkdir(parents=True, exist_ok=True)
        for old in out.glob("*.png"):
            if old.stem not in paths:
                old.unlink()
        for name, d in sorted(paths.items()):
            render(to_mpl_path(d), px).save(out / f"{name}.png", optimize=True)

    # Self-check: a hole cut by the nonzero rule must stay transparent.
    probe = Image.open(OUT / "56" / "water-outline.png").getchannel("A")
    if probe.getpixel((28, 36)) > 32:
        sys.exit("water-outline has no hole: the path fill rule is wrong")

    names = sorted(paths)
    lines = [
        "' GENERATED by roku/scripts/gen_glyphs.py. Do not edit; re-run the script.",
        "' MDI glyphs (Apache-2.0, fonts/MDI-LICENSE.txt) shipped as",
        "' pkg:/images/glyphs/<px>/<name>.png at " + ", ".join(f"{s}" for s in SIZES) + " px.",
        "function HK_GLYPHS() as object",
        "    return {",
    ]
    lines += [f'        "{n}": true' for n in names]
    lines += ["    }", "end function", ""]
    OUT_BRS.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} glyphs x {len(SIZES)} sizes -> {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
